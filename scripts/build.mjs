import { readFile, access } from 'node:fs/promises';
import { resolve } from 'node:path';
const root = resolve(import.meta.dirname, '..', 'dist');
const html = await readFile(resolve(root, 'index.html'), 'utf8');
const css = await readFile(resolve(root, 'styles.css'), 'utf8');
for (const file of ['styles.css','app.js','assets/logo.png','assets/mark.png','assets/social-cover.jpeg','robots.txt','sitemap.xml']) await access(resolve(root,file));
for (const [,asset] of html.matchAll(/(?:src|href)="(assets\/[^\"]+)"/g)) await access(resolve(root,asset));
for (const [,asset] of css.matchAll(/url\(['"]?(assets\/[^'"\)]+)['"]?\)/g)) await access(resolve(root,asset));
const ids = [...html.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]);
if (new Set(ids).size !== ids.length) throw new Error('Duplicate section IDs');
for(const [,id] of html.matchAll(/href="#([^"]+)"/g)) if(!ids.includes(id)) throw new Error('Missing anchor: '+id);
if(!html.includes('https://artha.aminosoftglobal.com/')) throw new Error('Artha link missing');
if((html.match(/<h1>/g)||[]).length!==1) throw new Error('Expected one main heading');
for(const meta of ['description','og:title','og:description','og:image','twitter:card']) if(!new RegExp(`(?:name|property)="${meta}" content="[^"]+"`).test(html)) throw new Error('Missing metadata: '+meta);
if(/mailto:|Email to be added|Telephone to be added|Address to be added|Social links coming soon/.test(html)) throw new Error('Remove outdated contact placeholders');
console.log('Production site ready in dist/. Assets, fonts, navigation, metadata, and Artha links verified.');
